#!/usr/bin/env python3
"""Data-derived revision tables, macros and publication figures."""
import csv
import json
from pathlib import Path
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

from journal_revision_common import ROOT, OUT, dump, sha, stamp

Q=ROOT/'manuscript_q1';T=Q/'tables';F=Q/'figures'


def table(name,caption,label,columns,header,rows,note=''):
    content=['% Generated by scripts/render_journal_validation.py',r'\begin{table*}[t]',r'\centering',r'\footnotesize',
             r'\caption{'+caption+'}',r'\label{'+label+'}',r'\begin{tabular}{'+columns+'}',r'\toprule',
             ' & '.join(header)+r'\\',r'\midrule']
    content+=[' & '.join(map(str,row))+r'\\' for row in rows]
    content+=[r'\bottomrule',r'\end{tabular}']
    if note:content+=[r'\par\smallskip\begin{minipage}{0.98\textwidth}\footnotesize '+note+r'\end{minipage}']
    content+=[r'\end{table*}']
    (T/name).write_text('\n'.join(content)+'\n')


def main():
    audit=json.loads((OUT/'endpoint_audit/summary.json').read_text())
    heuristic=json.loads((OUT/'heuristic/summary.json').read_text())
    replication=json.loads((OUT/'replication/study_summary.json').read_text())
    labels=['repository_mapping_supported','workflow_file_present','install_directive_observed','lockfile_present','dependency_version_supported']
    display=['All package mappings matched','Workflow file acquired','Aligned install directive','Relevant root lockfile','Dependency/version example']
    ar=[[d,audit['labels'][key]['supported_static'],audit['labels'][key]['unknown_requires_review']] for key,d in zip(labels,display)]
    table('revision_audit_table.tex','Automated evidence indicators in the stratified 120-endpoint sample.',
          'tab:revision_audit','lrr',['Evidence criterion','Candidate support','Unresolved'],ar,
          'The 115 acquired commits are current-time observations. Unresolved states are not negative or safe outcomes; automated indicators were not manually validated. All mappings assigned to an endpoint must match for the first criterion.')
    variants={'full_cap10':'Original rule (cap 10)','immediate_only':'Immediate + coverage',
              'no_coverage_tie':'No coverage tie-break','cap_1':'Cap 1','cap_5':'Cap 5','cap_20':'Cap 20','cap_all':'No candidate cap'}
    hr=[]
    for v,label in variants.items():
        row=next(r for r in heuristic['rows'] if r['budget']==100 and r['variant']==v)
        hr.append([label,f"{row['C']:,}",f"{row['H_pct']:.2f}",f"{row['P']:,}",f"{row['wall_seconds']:.2f}"])
    table('revision_heuristic_table.tex','Budget-100 component ablations on the original graph. Timing is one selection run in the same process.',
          'tab:revision_heuristic','lrrrr',['Rule',r'$C$',r'$H$ (\%)',r'$P$','Seconds'],hr,
          'Immediate + coverage omits reciprocal remaining-source scoring and is identical to the no-reciprocal variant. Thirty seeded tie runs each give $P=1{,}022$ at budget 100; this is selection variability on one graph, not ecosystem uncertainty.')
    er=[]
    for kind,label in [('empirical_candidate_restricted','Empirical candidate pools'),('synthetic','Synthetic overlap instances')]:
        rr=[r for r in heuristic['exact_rows'] if r['kind']==kind and r['method']=='direct_p']
        er.append([label,len(rr),sum(r['absolute_gap']==0 for r in rr),max(r['absolute_gap'] for r in rr),
                   f"{100*min(r['ratio'] for r in rr if r['ratio'] is not None):.2f}"])
    table('revision_exact_table.tex','Exact exclusion benchmarks with 20 eligible accounts and budgets 1, 3 and 5.',
          'tab:revision_exact','lrrrr',['Instance family','Settings','Exact hits','Worst gap',r'Min ratio (\%)'],er,
          'Twenty empirical pools and twelve synthetic instances each supply three correlated budget settings. Outside-candidate sources remain unselected. Optima apply only to the restricted instance; no full-graph approximation guarantee follows.')
    names={'portfolio':'Portfolio','exact_union':'Exact union','greedy_coverage':'Greedy coverage','direct_p':'Original direct P','immediate_only':'Immediate + coverage'}
    rr=[]
    for rep in ['name','version']:
        for method in ['portfolio','exact_union','greedy_coverage','direct_p','immediate_only']:
            r=next(r for r in replication['results'] if r['budget']==100 and r['selection_representation']==r['evaluation_representation']==rep and r['method']==method)
            rr.append([rep.title(),names[method],r['C'],f"{r['C_pct']:.2f}",f"{r['H_pct']:.2f}",r['P']])
    table('revision_replication_table.tex','Budget-100 results in the newly acquired bounded cohort: 66 workflow-associated repositories, 65 with observed sources.',
          'tab:revision_replication','llrrrr',['Representation','Rule',r'$C$',r'$C$ (\%)',r'$H$ (\%)',r'$P$'],rr,
          'The cohort has 1,051 observed accounts. H denominators are 2,494 name pairs and 2,411 version pairs. Root selection comes from the original ordinary-name frame; acquisition failures remain recorded and six missing dependency graphs are not treated as empty graphs.')
    cr=[]
    for r in replication['common_results']:
        if r['budget']==100:
            cr.append(['Original' if r['dataset']=='original' else 'New cohort',names[r['method']],r['C'],f"{r['H_pct']:.2f}",r['P'],f"{r['pair_denominator']:,}"])
    table('revision_common_table.tex','Reoptimized budget-100 selections on 65 common repository keys with 1,036 common selectable accounts.',
          'tab:revision_common','llrrrr',['Dataset','Rule',r'$C$',r'$H$ (\%)',r'$P$','Pair mass'],cr,
          'Complete source sets are preserved, including sources outside the common eligible account set. Pair denominators differ by observed graph, so H percentages are within-dataset quantities rather than a causal temporal effect.')
    macros={'AuditSample':120,'AuditCommits':audit['commits_acquired'],'HeuristicExactHits':heuristic['direct_exact_hits'],
            'HeuristicExactSettings':heuristic['direct_benchmarks'],'HeuristicWorstGap':heuristic['direct_worst_absolute_gap'],
            'ReplicationEndpoints':replication['workflow_repository_endpoints'],'ReplicationAccounts':replication['maintainers'],
            'ReplicationPairDecrease':f"{replication['pair_decrease_pct']:.2f}",
            'ReplicationGreedyC':next(r['C'] for r in replication['results'] if r['method']=='greedy_coverage' and r['budget']==100 and r['selection_representation']==r['evaluation_representation']=='name'),
            'ReplicationUnionC':next(r['C'] for r in replication['results'] if r['method']=='exact_union' and r['budget']==100 and r['selection_representation']==r['evaluation_representation']=='name')}
    (Q/'config/revision_numbers.tex').write_text('% Generated revision evidence\n'+'\n'.join('\\newcommand{\\'+k+'}{'+str(v)+'}' for k,v in macros.items())+'\n')
    plt.rcParams.update({'font.family':'DejaVu Sans','font.size':8,'pdf.fonttype':42,'ps.fonttype':42,'axes.spines.top':False,'axes.spines.right':False})
    fig,axs=plt.subplots(1,2,figsize=(7.1,3.4));fig.subplots_adjust(left=.18,right=.97,bottom=.25,top=.86,wspace=.65)
    y=np.arange(5);positive=np.array([audit['labels'][k]['supported_static'] for k in labels])
    axs[0].barh(y,positive,color='#2b6686',label='Automated candidate')
    axs[0].barh(y,120-positive,left=positive,color='#dedede',label='Unresolved')
    for i,v in enumerate(positive):axs[0].text(v/2,i,str(v),ha='center',va='center',color='white',fontsize=8)
    axs[0].set_yticks(y,['Mappings','Workflow file','Install directive','Root lockfile','Version example']);axs[0].invert_yaxis()
    axs[0].set(xlim=(0,120),xlabel='Sampled endpoints',title='(a) Automated evidence')
    handles,legend_labels=axs[0].get_legend_handles_labels()
    fig.legend(handles,legend_labels,loc='lower center',bbox_to_anchor=(.5,.015),frameon=False,fontsize=7,ncol=2)
    for kind,label,color in [('empirical_candidate_restricted','Empirical (60 settings)','#285d85'),('synthetic','Synthetic (36 settings)','#b57720')]:
        vals=sorted(r['absolute_gap'] for r in heuristic['exact_rows'] if r['kind']==kind and r['method']=='direct_p')
        axs[1].step(vals,np.arange(1,len(vals)+1)/len(vals),where='post',label=label,color=color)
    axs[1].set_xscale('symlog',linthresh=1);axs[1].set(ylim=(0,1.03),xlabel='Exact P minus heuristic P',ylabel='Fraction at or below gap',title='(b) Restricted exact gaps')
    axs[1].set_xticks([0,1,5,20,66],['0','1','5','20','66']);axs[1].legend(frameon=False,fontsize=7,loc='lower right');axs[1].grid(alpha=.15)
    for ext in ['pdf','png','svg']:
        path=F/f'revision_audit_benchmarks.{ext}';fig.savefig(path,dpi=200)
        if ext=='svg':path.write_text('\n'.join(line.rstrip() for line in path.read_text().splitlines())+'\n')
    plt.close(fig)
    fig,axs=plt.subplots(1,3,figsize=(7.1,2.8));fig.subplots_adjust(left=.08,right=.97,bottom=.24,top=.83,wspace=.45)
    for ax,field,title in zip(axs,['C_pct','H_pct','P'],['(a) Coverage (%)','(b) Exposure share (%)','(c) All-source exclusions']):
        for method,color,label in [('greedy_coverage','#00858b','Greedy'),('exact_union','#285d85','Union'),('direct_p','#b57720','Direct P')]:
            rr=[r for r in replication['results'] if r['method']==method and r['selection_representation']==r['evaluation_representation']=='name']
            ax.plot([r['budget'] for r in rr],[r[field] for r in rr],marker='o',ms=2.5,lw=1.2,color=color,label=label)
        ax.set_xscale('log');ax.set_xticks([1,5,10,25,50,100],['1','5','10','25','50','100']);ax.set(xlabel='Account budget',title=title);ax.set_title(title,fontsize=8);ax.grid(alpha=.15)
    axs[0].legend(frameon=False,fontsize=7,loc='upper left')
    for ext in ['pdf','png','svg']:
        path=F/f'revision_replication.{ext}';fig.savefig(path,dpi=200)
        if ext=='svg':path.write_text('\n'.join(line.rstrip() for line in path.read_text().splitlines())+'\n')
    plt.close(fig)
    record={'created_at_utc':stamp(),'renderer_sha256':sha(__file__),
            'source_sha256':{str(p.relative_to(ROOT)):sha(p) for p in [OUT/'endpoint_audit/summary.json',OUT/'heuristic/summary.json',OUT/'replication/study_summary.json']},
            'figures':{stem:{ext:sha(F/f'{stem}.{ext}') for ext in ['pdf','png','svg']} for stem in ['revision_audit_benchmarks','revision_replication']},
            'tables':{p.name:sha(p) for p in T.glob('revision_*_table.tex')}}
    dump(OUT/'publication_artifacts.json',record)
    print('Generated five revision tables, two figures and shared numeric macros')


if __name__=='__main__':main()
